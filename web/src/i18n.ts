export type TKey = keyof typeof en
export type T = (key: TKey, vars?: Record<string, string | number>) => string

const DICTS: Record<UiLang, Dict> = { en, es, fr, pt, de, it }

/** UI strings in `lang`; languages without a dictionary (added by hand) get English menus. */
export function makeT(lang: string): T {
  const dict = DICTS[lang as UiLang] ?? en
  return (key, vars) => (dict[key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k) => String(vars?.[k] ?? ''))
}
